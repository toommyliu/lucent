const buildDeclarationMap = (
  program: ts.Program,
): ReadonlyMap<string, ts.InterfaceDeclaration | ts.TypeAliasDeclaration> => {
  const declarations = new Map<
    string,
    ts.InterfaceDeclaration | ts.TypeAliasDeclaration
  >();

  const declarationRank = (
    declaration: ts.InterfaceDeclaration | ts.TypeAliasDeclaration,
  ): number => {
    const fileName = declaration.getSourceFile().fileName.replaceAll("\\", "/");
    return (
      (fileName.includes("/dist/") ? 10 : 0) +
      (/\.d\.[cm]?ts$/.test(fileName) ? 5 : 0)
    );
  };

  const visit = (node: ts.Node): void => {
    if (ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)) {
      const current = declarations.get(node.name.text);
      if (current === undefined || declarationRank(node) < declarationRank(current)) {
        declarations.set(node.name.text, node);
      }
    }
    ts.forEachChild(node, visit);
  };

  for (const sourceFile of program.getSourceFiles()) {
    if (sourceFile.fileName.includes("/node_modules/")) {
      continue;
    }
    visit(sourceFile);
  }

  return declarations;
};

const getInterface = (
  declarations: ReadonlyMap<
    string,
    ts.InterfaceDeclaration | ts.TypeAliasDeclaration
  >,
  name: string,
  seen = new Set<string>(),
): ts.InterfaceDeclaration => {
  if (seen.has(name)) {
    fail(`Unable to resolve circular interface alias ${name}`);
  }

  const declaration =
    declarations.get(name) ?? fail(`Unable to find interface ${name}`);

  if (ts.isInterfaceDeclaration(declaration)) {
    return declaration;
  }

  const reference = parseTypeReference(declaration.type);
  if (reference) {
    const nextSeen = new Set(seen);
    nextSeen.add(name);
    const omitted = resolveOmitInterfaceAlias(
      reference,
      (targetName) => getInterface(declarations, targetName, nextSeen),
      { referenceName: "unqualifiedName" },
    );
    if (omitted) {
      return omitted;
    }
    return getInterface(declarations, reference.unqualifiedName, nextSeen);
  }

  return fail(`Unable to find interface ${name}`);
};

const typeText = (
  node: ts.TypeNode | undefined,
  sourceFile: ts.SourceFile,
): string => (node === undefined ? "unknown" : node.getText(sourceFile));

const splitTopLevel = (value: string, delimiter = ","): string[] => {
  const parts: string[] = [];
  let depth = 0;
  let start = 0;

  for (let index = 0; index < value.length; index += 1) {
    const char = value[index];
    if (char === "<" || char === "(" || char === "[" || char === "{") {
      depth += 1;
    } else if (char === ">" || char === ")" || char === "]" || char === "}") {
      depth = Math.max(0, depth - 1);
    } else if (char === delimiter && depth === 0) {
      parts.push(value.slice(start, index).trim());
      start = index + 1;
    }
  }

  parts.push(value.slice(start).trim());
  return parts;
};

const isEffectTypeNode = (node: ts.TypeNode | undefined): boolean => {
  const reference = parseTypeReference(node);
  if (!reference) {
    return false;
  }
  return reference.unqualifiedName === "Effect" && reference.args.length >= 1;
};

const expressionNameText = (node: ts.Expression): string | null => {
  if (ts.isIdentifier(node)) {
    return node.text;
  }

  if (ts.isPropertyAccessExpression(node)) {
    const left = expressionNameText(node.expression);
    return left === null ? node.name.text : `${left}.${node.name.text}`;
  }

  return null;
};

const unqualifiedExpressionName = (node: ts.Expression): string | null => {
  if (ts.isIdentifier(node)) {
    return node.text;
  }

  if (ts.isPropertyAccessExpression(node)) {
    return node.name.text;
  }

  return null;
};

const parseHeritageReference = (
  node: ts.ExpressionWithTypeArguments,
): TypeReferenceInfo | null => {
  const name = expressionNameText(node.expression);
  const unqualifiedName = unqualifiedExpressionName(node.expression);
  if (name === null || unqualifiedName === null) {
    return null;
  }

  return {
    name,
    unqualifiedName,
    args: Array.from(node.typeArguments ?? []),
  };
};

const formatResolvedType = (
  checker: ts.TypeChecker,
  type: ts.Type,
  node: ts.Node,
): string =>
  checker
    .typeToString(
      type,
      node,
      ts.TypeFormatFlags.NoTruncation |
        ts.TypeFormatFlags.UseSingleQuotesForStringLiteralType,
    )
    .replace(/import\(["'][^"']+["']\)\./g, "");

const formatType = (
  checker: ts.TypeChecker,
  node: ts.TypeNode | undefined,
): string => {
  if (node === undefined) {
    return "unknown";
  }

  return formatResolvedType(checker, checker.getTypeAtLocation(node), node);
};

const parseEffectReturn = (
  raw: string,
  node: ts.TypeNode | undefined,
  sourceFile: ts.SourceFile,
): ReturnDoc => {
  const reference = parseTypeReference(node);
  if (reference?.unqualifiedName === "Effect" && reference.args.length >= 1) {
    return {
      raw,
      result: typeText(reference.args[0], sourceFile),
      error:
        reference.args.length >= 2
          ? typeText(reference.args[1], sourceFile)
          : "never",
    };
  }

  if (
    reference?.unqualifiedName === "BridgeEffect" &&
    reference.args.length >= 1
  ) {
    return {
      raw,
      result: typeText(reference.args[0], sourceFile),
      error: "BridgeError",
    };
  }

  if (
    reference?.unqualifiedName === "ArmyEffect" &&
    reference.args.length >= 1
  ) {
    const extraError =
      reference.args.length >= 2
        ? `${typeText(reference.args[1], sourceFile)} | `
        : "";
    return {
      raw,
      result: typeText(reference.args[0], sourceFile),
      error: `${extraError}ArmyError | BridgeError`,
    };
  }

  const effectMatch = /^(?:Effect\.)?Effect<(.+)>$/.exec(raw);
  if (effectMatch?.[1]) {
    const args = splitTopLevel(effectMatch[1]);
    return {
      raw,
      result: args[0] ?? "unknown",
      error: args[1] ?? "never",
    };
  }

  return { raw, result: null, error: null };
};

const getReturnDoc = (
  checker: ts.TypeChecker,
  node: ts.SignatureDeclaration,
): ReturnDoc => {
  const sourceFile = node.getSourceFile();
  const raw =
    node.type === undefined
      ? checker.typeToString(
          checker.getSignatureFromDeclaration(node)?.getReturnType() ??
            checker.getAnyType(),
          node,
          ts.TypeFormatFlags.NoTruncation,
        )
      : formatType(checker, node.type);

  return parseEffectReturn(raw, node.type, sourceFile);
};

const getParameterDocs = (
  checker: ts.TypeChecker,
  node: ts.SignatureDeclaration,
): ParameterDoc[] => {
  const descriptions = getParamDescriptions(node);
  const sourceFile = node.getSourceFile();

  return node.parameters.map((parameter) => {
    const name = parameter.name.getText(sourceFile);
    return {
      name,
      type: formatType(checker, parameter.type),
      required:
        parameter.questionToken === undefined &&
        parameter.initializer === undefined &&
        parameter.dotDotDotToken === undefined,
      rest: parameter.dotDotDotToken !== undefined,
      description: descriptions.get(name) ?? "",
    };
  });
};

const methodSignature = (
  path: string,
  parameters: readonly ParameterDoc[],
  returnDoc: ReturnDoc,
): string =>
  `${path}(${parameters
    .map(
      (parameter) =>
        `${parameter.rest ? "..." : ""}${parameter.name}${
          parameter.required ? "" : "?"
        }: ${parameter.type}`,
    )
    .join(", ")}): ${returnDoc.raw}`;

const collectTypeReferences = (
  node: ts.Node | undefined,
  output: Set<string>,
): void => {
  if (node === undefined) {
    return;
  }

  if (ts.isTypeReferenceNode(node)) {
    const name = parseTypeReference(node)?.unqualifiedName;
    if (
      name &&
      !TYPE_REFERENCE_WRAPPERS.has(name) &&
      !BUILTIN_TYPE_NAMES.has(name)
    ) {
      output.add(name);
    }
  }

  ts.forEachChild(node, (child) => collectTypeReferences(child, output));
};

const expandTypeReferences = (
  declarations: ReadonlyMap<
    string,
    ts.InterfaceDeclaration | ts.TypeAliasDeclaration
  >,
  roots: ReadonlySet<string>,
): ReadonlySet<string> => {
  const expanded = new Set(roots);
  const pending = Array.from(roots);

  for (let index = 0; index < pending.length; index += 1) {
    const name = pending[index];
    if (name === undefined) {
      continue;
    }

    const declaration = declarations.get(name);
    if (declaration === undefined) {
      continue;
    }

    const nested = new Set<string>();
    collectTypeReferences(declaration, nested);
    if (ts.isInterfaceDeclaration(declaration)) {
      for (const clause of declaration.heritageClauses ?? []) {
        for (const heritage of clause.types) {
          const reference = parseHeritageReference(heritage);
          if (reference !== null) {
            nested.add(reference.unqualifiedName);
          }
        }
      }
    }

    for (const reference of nested) {
      if (
        expanded.has(reference) ||
        BUILTIN_TYPE_NAMES.has(reference) ||
        TYPE_REFERENCE_WRAPPERS.has(reference)
      ) {
        continue;
      }
      expanded.add(reference);
      pending.push(reference);
    }
  }

  return expanded;
};

const resolveNestedInterface = (
  declarations: ReadonlyMap<
    string,
    ts.InterfaceDeclaration | ts.TypeAliasDeclaration
  >,
  node: ts.TypeNode | undefined,
): ts.InterfaceDeclaration | null => {
  const reference = parseTypeReference(node);
  if (!reference) {
    return null;
  }

  const declaration = declarations.get(reference.unqualifiedName);
  return declaration && ts.isInterfaceDeclaration(declaration)
    ? declaration
    : null;
};

const resolveInheritedInterface = (
  declarations: ReadonlyMap<
    string,
    ts.InterfaceDeclaration | ts.TypeAliasDeclaration
  >,
  heritage: ts.ExpressionWithTypeArguments,
): ts.InterfaceDeclaration | null => {
  const reference = parseHeritageReference(heritage);
  if (reference === null) {
    return null;
  }

  const omitted = resolveOmitInterfaceAlias(
    reference,
    (targetName) => getInterface(declarations, targetName),
    { referenceName: "unqualifiedName" },
  );
  if (omitted !== null) {
    return omitted;
  }

  if (reference.unqualifiedName === "Pick") {
    return null;
  }

  const declaration = declarations.get(reference.unqualifiedName);
  if (declaration === undefined) {
    return null;
  }

  return ts.isInterfaceDeclaration(declaration)
    ? declaration
    : getInterface(declarations, reference.unqualifiedName);
};

const collectInterfaceMemberNames = (
  declaration: ts.InterfaceDeclaration,
): ReadonlySet<string> => {
  const names = new Set<string>();
  for (const member of declaration.members) {
    if (!ts.isMethodSignature(member) && !ts.isPropertySignature(member)) {
      continue;
    }

    const name = getPropertyName(member.name);
    if (name !== null) {
      names.add(name);
    }
  }
  return names;
};

const topLevelPathMember = (basePath: string, path: string): string => {
  const prefix = `${basePath}.`;
  return path.startsWith(prefix)
    ? (path.slice(prefix.length).split(".")[0] ?? path)
    : path;
};

const collectMembersFromInterface = (
  checker: ts.TypeChecker,
  declarations: ReadonlyMap<
    string,
    ts.InterfaceDeclaration | ts.TypeAliasDeclaration
  >,
  options: CliOptions,
  git: GitSourceInfo | null,
  declaration: ts.InterfaceDeclaration,
  basePath: string,
  typeReferences: Set<string>,
  seenInterfaces = new Set<string>(),
): MemberDoc[] => {
  if (seenInterfaces.has(declaration.name.text)) {
    return [];
  }

  const nextSeen = new Set(seenInterfaces);
  nextSeen.add(declaration.name.text);
  const docs: MemberDoc[] = [];
  const ownMemberNames = collectInterfaceMemberNames(declaration);

  for (const heritageClause of declaration.heritageClauses ?? []) {
    if (heritageClause.token !== ts.SyntaxKind.ExtendsKeyword) {
      continue;
    }

    for (const heritage of heritageClause.types) {
      const inheritedInterface = resolveInheritedInterface(
        declarations,
        heritage,
      );
      if (inheritedInterface === null) {
        continue;
      }

      docs.push(
        ...collectMembersFromInterface(
          checker,
          declarations,
          options,
          git,
          inheritedInterface,
          basePath,
          typeReferences,
          nextSeen,
        ).filter(
          (doc) =>
            !ownMemberNames.has(topLevelPathMember(basePath, doc.path)),
        ),
      );
    }
  }

  for (const member of declaration.members) {
    if (ts.isMethodSignature(member)) {
      const name = getPropertyName(member.name);
      if (name === null) {
        continue;
      }

      const parameters = getParameterDocs(checker, member);
      const returnDoc = getReturnDoc(checker, member);
      for (const parameter of member.parameters) {
        collectTypeReferences(parameter.type, typeReferences);
      }
      collectTypeReferences(member.type, typeReferences);

      const path = `${basePath}.${name}`;
      docs.push({
        path,
        name,
        kind: "method",
        summary: getSummary(member),
        signature: methodSignature(path, parameters, returnDoc),
        parameters,
        returnDoc,
        ...getSourceInfo(options, git, member),
      });
      continue;
    }

    if (!ts.isPropertySignature(member)) {
      continue;
    }

    const name = getPropertyName(member.name);
    if (name === null) {
      continue;
    }

    const nestedInterface = resolveNestedInterface(declarations, member.type);
    if (nestedInterface !== null && !isEffectTypeNode(member.type)) {
      docs.push(
        ...collectMembersFromInterface(
          checker,
          declarations,
          options,
          git,
          nestedInterface,
          `${basePath}.${name}`,
          typeReferences,
          nextSeen,
        ),
      );
      continue;
    }

    if (member.type && ts.isFunctionTypeNode(member.type)) {
      const parameters = getParameterDocs(checker, member.type);
      const returnDoc = getReturnDoc(checker, member.type);
      for (const parameter of member.type.parameters) {
        collectTypeReferences(parameter.type, typeReferences);
      }
      collectTypeReferences(member.type.type, typeReferences);

      const path = `${basePath}.${name}`;
      docs.push({
        path,
        name,
        kind: "method",
        summary: getSummary(member),
        signature: methodSignature(path, parameters, returnDoc),
        parameters,
        returnDoc,
        ...getSourceInfo(options, git, member),
      });
      continue;
    }

    collectTypeReferences(member.type, typeReferences);

    const returnDoc = parseEffectReturn(
      formatType(checker, member.type),
      member.type,
      member.getSourceFile(),
    );
    docs.push({
      path: `${basePath}.${name}`,
      name,
      kind: returnDoc.result === null ? "value" : "effect",
      summary: getSummary(member),
      signature: `${basePath}.${name}: ${returnDoc.raw}`,
      parameters: [],
      returnDoc,
      ...getSourceInfo(options, git, member),
    });
  }

  return docs.sort((a, b) => a.path.localeCompare(b.path));
};

const getSymbolDeclaration = (symbol: ts.Symbol): ts.Declaration | null =>
  symbol.valueDeclaration ?? symbol.declarations?.[0] ?? null;

const getSymbolSummary = (
  checker: ts.TypeChecker,
  symbol: ts.Symbol,
  declaration: ts.Declaration | null,
  signatureDeclaration?: ts.SignatureDeclaration,
): string =>
  (declaration === null ? "" : getSummary(declaration)) ||
  ts.displayPartsToString(symbol.getDocumentationComment(checker)).trim() ||
  (signatureDeclaration === undefined
    ? ""
    : getSummary(signatureDeclaration));

const isDocumentableSymbol = (
  options: CliOptions,
  symbol: ts.Symbol,
): boolean =>
  (symbol.declarations ?? []).some((declaration) => {
    const fileName = declaration.getSourceFile().fileName;
    return (
      isInsideRepo(options.repoRoot, fileName) &&
      !fileName.includes("/node_modules/") &&
      !fileName.endsWith(".test.ts")
    );
  });

const getSignatureParameterDocs = (
  checker: ts.TypeChecker,
  signature: ts.Signature,
  fallbackNode: ts.Node,
): ParameterDoc[] =>
  signature.getParameters().map((parameter) => {
    const declaration = getSymbolDeclaration(parameter);
    const typeNode = declaration ?? fallbackNode;
    const parameterDeclaration =
      declaration !== null && ts.isParameter(declaration)
        ? declaration
        : null;
    const description = ts
      .displayPartsToString(parameter.getDocumentationComment(checker))
      .trim();

    return {
      name: parameter.name,
      type: formatResolvedType(
        checker,
        checker.getTypeOfSymbolAtLocation(parameter, typeNode),
        typeNode,
      ),
      required:
        (parameter.flags & ts.SymbolFlags.Optional) === 0 &&
        parameterDeclaration?.questionToken === undefined &&
        parameterDeclaration?.initializer === undefined &&
        parameterDeclaration?.dotDotDotToken === undefined,
      rest: parameterDeclaration?.dotDotDotToken !== undefined,
      description,
    };
  });

const collectTaggedTypeReferences = (
  checker: ts.TypeChecker,
  node: ts.Node,
  references: Set<string>,
): void => {
  if (ts.isTypeReferenceNode(node)) {
    const referenced = checker.getSymbolAtLocation(node.typeName);
    const symbol =
      referenced !== undefined &&
      (referenced.flags & ts.SymbolFlags.Alias) !== 0
        ? checker.getAliasedSymbol(referenced)
        : referenced;
    if (
      symbol !== undefined &&
      (symbol.declarations ?? []).some((declaration) =>
        ts
          .getJSDocTags(declaration)
          .some((tag) => tag.tagName.text === "scriptingExpandSchema"),
      )
    ) {
      references.add(symbol.name);
    }
  }

  ts.forEachChild(node, (child) =>
    collectTaggedTypeReferences(checker, child, references),
  );
};

const collectMembersFromType = (
  checker: ts.TypeChecker,
  options: CliOptions,
  git: GitSourceInfo | null,
  type: ts.Type,
  fallbackNode: ts.Node,
  basePath: string,
  typeReferences: Set<string>,
  seenTypes = new Set<ts.Type>(),
): MemberDoc[] => {
  if (seenTypes.has(type)) {
    return [];
  }

  const nextSeen = new Set(seenTypes);
  nextSeen.add(type);
  const docs: MemberDoc[] = [];

  for (const symbol of checker.getPropertiesOfType(type)) {
    const name = symbol.getName();
    const declaration = getSymbolDeclaration(symbol);
    const sourceNode = declaration ?? fallbackNode;
    const memberType = checker.getTypeOfSymbolAtLocation(symbol, sourceNode);
    const signatures = memberType.getCallSignatures();
    const path = `${basePath}.${name}`;

    if (signatures.length > 0) {
      const signature = signatures[0]!;
      const signatureDeclaration = signature.getDeclaration();
      const signatureNode = signatureDeclaration ?? sourceNode;
      const parameters = getSignatureParameterDocs(
        checker,
        signature,
        signatureNode,
      );
      const rawReturn = formatResolvedType(
        checker,
        signature.getReturnType(),
        signatureNode,
      );
      const returnDoc = parseEffectReturn(
        rawReturn,
        signatureDeclaration?.type,
        signatureNode.getSourceFile(),
      );

      for (const parameter of parameters) {
        collectTypeNameTokens(parameter.type, typeReferences);
      }
      for (const parameter of signatureDeclaration?.parameters ?? []) {
        if (parameter.type !== undefined) {
          collectTaggedTypeReferences(
            checker,
            parameter.type,
            typeReferences,
          );
        }
      }
      collectTypeNameTokens(rawReturn, typeReferences);

      docs.push({
        path,
        name,
        kind: "method",
        summary: getSymbolSummary(
          checker,
          symbol,
          declaration,
          signatureDeclaration,
        ),
        signature: methodSignature(path, parameters, returnDoc),
        parameters,
        returnDoc,
        ...getSourceInfo(options, git, sourceNode),
      });
      continue;
    }

    const rawType = formatResolvedType(checker, memberType, sourceNode);
    const returnDoc = parseEffectReturn(
      rawType,
      declaration !== null && ts.isPropertySignature(declaration)
        ? declaration.type
        : undefined,
      sourceNode.getSourceFile(),
    );
    const nestedSymbols = checker
      .getPropertiesOfType(memberType)
      .filter((nested) => isDocumentableSymbol(options, nested));
    if (returnDoc.result === null && nestedSymbols.length > 0) {
      docs.push(
        ...collectMembersFromType(
          checker,
          options,
          git,
          memberType,
          sourceNode,
          path,
          typeReferences,
          nextSeen,
        ),
      );
      continue;
    }

    collectTypeNameTokens(rawType, typeReferences);
    docs.push({
      path,
      name,
      kind: returnDoc.result === null ? "value" : "effect",
      summary: getSymbolSummary(checker, symbol, declaration),
      signature: `${path}: ${rawType}`,
      parameters: [],
      returnDoc,
      ...getSourceInfo(options, git, sourceNode),
    });
  }

  return docs.sort((left, right) => left.path.localeCompare(right.path));
};

const collectApiGroups = (
  checker: ts.TypeChecker,
  declarations: ReadonlyMap<
    string,
    ts.InterfaceDeclaration | ts.TypeAliasDeclaration
  >,
  options: CliOptions,
  git: GitSourceInfo | null,
): {
  readonly runtimeHelpers: readonly MemberDoc[];
  readonly namespaces: readonly ApiNamespace[];
  readonly groups: readonly ApiGroup[];
  readonly typeReferences: readonly string[];
} => {
  const scriptApi = getInterface(declarations, "ScriptApi");
  const scriptRuntimeApi = getInterface(declarations, "ScriptRuntimeApi");
  const helperTypeReferences = new Set<string>();
  const groups: ApiGroup[] = [];

  const runtimeHelpers = collectMembersFromInterface(
    checker,
    declarations,
    options,
    git,
    scriptRuntimeApi,
    "script",
    helperTypeReferences,
  );

  const namespaces: ApiNamespace[] = [];
  for (const member of scriptApi.members) {
    if (!ts.isPropertySignature(member)) {
      continue;
    }

    const name = getPropertyName(member.name);
    if (name === null) {
      continue;
    }

    const typeReferences = new Set<string>();
    const shapeType = checker.getTypeAtLocation(member.type ?? member);
    const members = collectMembersFromType(
      checker,
      options,
      git,
      shapeType,
      member,
      `api.${name}`,
      typeReferences,
    );
    if (members.length === 0) {
      continue;
    }

    const id = `api/${kebabCase(name)}`;
    namespaces.push({
      name,
      slug: kebabCase(name),
      href: `/scripting/api/${kebabCase(name)}/`,
      sourceType: formatType(checker, member.type),
    });
    const summary = getSummary(member);
    groups.push({
      id,
      title: `api.${name}`,
      label: titleCase(name),
      description: summary || "",
      summary,
      members,
      typeReferences: Array.from(typeReferences),
    });
  }

  const scriptFeaturesApi = getInterface(declarations, "ScriptFeaturesApi");
  for (const member of scriptFeaturesApi.members) {
    if (!ts.isPropertySignature(member)) {
      continue;
    }

    const name = getPropertyName(member.name);
    if (name === null) {
      continue;
    }

    const typeReferences = new Set<string>();
    const members = collectMembersFromType(
      checker,
      options,
      git,
      checker.getTypeAtLocation(member.type ?? member),
      member,
      `features.${name}`,
      typeReferences,
    );
    if (members.length === 0) {
      continue;
    }

    const summary = getSummary(member) || "";
    groups.push({
      id: `features/${kebabCase(name)}`,
      title: `features.${name}`,
      label: titleCase(name),
      description: summary,
      summary,
      members,
      typeReferences: Array.from(typeReferences),
    });
  }

  const documentedTypeReferences = new Set([
    ...helperTypeReferences,
    ...groups.flatMap((group) => group.typeReferences),
  ]);
  for (const member of [
    ...runtimeHelpers,
    ...groups.flatMap((group) => group.members),
  ]) {
    for (const parameter of member.parameters) {
      collectTypeNameTokens(parameter.type, documentedTypeReferences);
    }
    collectTypeNameTokens(member.returnDoc.raw, documentedTypeReferences);
    if (member.returnDoc.result !== null) {
      collectTypeNameTokens(member.returnDoc.result, documentedTypeReferences);
    }
    if (member.returnDoc.error !== null) {
      collectTypeNameTokens(member.returnDoc.error, documentedTypeReferences);
    }
  }

  return {
    runtimeHelpers,
    namespaces: namespaces.sort((a, b) => a.name.localeCompare(b.name)),
    groups: groups.sort((a, b) => a.id.localeCompare(b.id)),
    typeReferences: Array.from(documentedTypeReferences),
  };
};

const walkReflection = (
  reflection: Reflection,
  visit: (reflection: Reflection) => void,
): void => {
  visit(reflection);
  if (!reflection.isContainer()) {
    return;
  }
  for (const child of reflection.children ?? []) {
    walkReflection(child, visit);
  }
};

const reflectionSource = (
  options: CliOptions,
  git: GitSourceInfo | null,
  reflection: DeclarationReflection | SignatureReflection,
): SourceInfo => {
  const source = reflection.sources?.[0];
  if (source === undefined) {
    return {
      sourcePath: "unknown",
      sourceLine: 1,
      sourceUrl: null,
    };
  }

  const sourceFileName = source.fullFileName || source.fileName;
  const fullPath = isAbsolute(sourceFileName)
    ? sourceFileName
    : resolve(options.repoRoot, sourceFileName);
  const sourcePath = relative(options.repoRoot, fullPath).replaceAll("\\", "/");
  return {
    sourcePath,
    sourceLine: source.line,
    sourceUrl: buildSourceUrl(git, options.repoRoot, fullPath, source.line),
  };
};

const commentText = (reflection: Reflection | undefined): string => {
  const parts = reflection?.comment?.summary ?? [];
  return parts
    .map((part) => ("text" in part ? part.text : ""))
    .join("")
    .trim();
};

const typeToString = (type: SomeType | undefined): string =>
  type?.toString() ?? "unknown";

const typeParametersText = (
  typeParameters: DeclarationReflection["typeParameters"],
): string =>
  typeParameters === undefined || typeParameters.length === 0
    ? ""
    : `<${typeParameters.map((parameter) => parameter.name).join(", ")}>`;

const typedocKindName = (kind: ReflectionKind): string =>
  ReflectionKind.singularString(kind).toString().toLowerCase();

const isDocumentableTypeReflection = (
  reflection: Reflection,
): reflection is DeclarationReflection =>
  reflection.isDeclaration() &&
  (reflection.kind === ReflectionKind.Class ||
    reflection.kind === ReflectionKind.Interface ||
    reflection.kind === ReflectionKind.TypeAlias ||
    reflection.kind === ReflectionKind.Enum);

const reflectionRank = (reflection: DeclarationReflection): number => {
  const sourcePenalty = reflection.sources?.some((source) =>
    source.fullFileName.includes("/dist/"),
  )
    ? 10
    : 0;

  switch (reflection.kind) {
    case ReflectionKind.Class:
      return sourcePenalty;
    case ReflectionKind.Interface:
      return sourcePenalty + 1;
    case ReflectionKind.TypeAlias:
      return sourcePenalty + 2;
    case ReflectionKind.Enum:
      return sourcePenalty + 3;
    default:
      return sourcePenalty + 4;
  }
};

const isDocSourceReflection = (
  options: CliOptions,
  reflection: DeclarationReflection,
): boolean => {
  const source = reflection.sources?.[0];
  if (source === undefined) {
    return false;
  }

  const sourceFileName = source.fullFileName || source.fileName;
  const fullPath = isAbsolute(sourceFileName)
    ? sourceFileName
    : resolve(options.repoRoot, sourceFileName);
  if (!isInsideRepo(options.repoRoot, fullPath)) {
    return false;
  }

  const relativePath = relative(options.repoRoot, fullPath).replaceAll(
    "\\",
    "/",
  );
  return (
    relativePath.startsWith("app/src/shared/") ||
    relativePath.startsWith("app/src/renderer/apps/game/") ||
    relativePath.startsWith("packages/core/src/") ||
    relativePath.startsWith("packages/game/src/")
  );
};

const buildTypeReflectionMap = (
  options: CliOptions,
  project: ProjectReflection,
): ReadonlyMap<string, DeclarationReflection> => {
  const reflections = new Map<string, DeclarationReflection>();
  walkReflection(project, (reflection) => {
    if (
      !isDocumentableTypeReflection(reflection) ||
      !isDocSourceReflection(options, reflection)
    ) {
      return;
    }

    const current = reflections.get(reflection.name);
    if (
      current === undefined ||
      reflectionRank(reflection) < reflectionRank(current)
    ) {
      reflections.set(reflection.name, reflection);
    }
  });
  return reflections;
};

const collectTypeNameTokens = (text: string, output: Set<string>): void => {
  for (const match of text.matchAll(/\b[A-Za-z_$][A-Za-z0-9_$]*\b/g)) {
    const token = match[0];
    if (!BUILTIN_TYPE_NAMES.has(token) && !TYPE_REFERENCE_WRAPPERS.has(token)) {
      output.add(token);
    }
  }
};

const getInheritedFrom = (reflection: DeclarationReflection): string | null => {
  const inherited = reflection.inheritedFrom;
  if (inherited === undefined) {
    return null;
  }

  const parent = inherited.reflection?.parent;
  if (parent !== undefined && parent.name !== reflection.parent?.name) {
    return parent.name;
  }

  const qualified = inherited.qualifiedName;
  const parts = qualified.split(".");
  return parts.length > 1 ? (parts[parts.length - 2] ?? null) : inherited.name;
};

const methodSignatureText = (
  method: DeclarationReflection,
  signature: SignatureReflection,
): string => {
  const typeParameters =
    signature.typeParameters === undefined ||
    signature.typeParameters.length === 0
      ? ""
      : `<${signature.typeParameters.map((parameter) => parameter.name).join(", ")}>`;
  const parameters = (signature.parameters ?? [])
    .map((parameter) => {
      const rest = parameter.flags.isRest ? "..." : "";
      const optional = parameter.flags.isOptional ? "?" : "";
      return `${rest}${parameter.name}${optional}: ${typeToString(parameter.type)}`;
    })
    .join(", ");
  return `${method.name}${typeParameters}(${parameters}): ${typeToString(
    signature.type,
  )}`;
};

const declarationDefinition = (reflection: DeclarationReflection): string => {
  const typeParameters = typeParametersText(reflection.typeParameters);
  switch (reflection.kind) {
    case ReflectionKind.Class: {
      const extended = reflection.extendedTypes?.[0];
      return `class ${reflection.name}${typeParameters}${
        extended === undefined ? "" : ` extends ${extended.toString()}`
      }`;
    }
    case ReflectionKind.Interface:
      return `interface ${reflection.name}${typeParameters}`;
    case ReflectionKind.TypeAlias:
      return `type ${reflection.name}${typeParameters} = ${typeToString(
        reflection.type,
      )}`;
    case ReflectionKind.Enum:
      return `enum ${reflection.name}`;
    default:
      return `${typedocKindName(reflection.kind)} ${reflection.name}`;
  }
};

const isVisibleInstanceMember = (reflection: DeclarationReflection): boolean =>
  !reflection.flags.isPrivate &&
  !reflection.flags.isProtected &&
  !reflection.flags.isStatic;

const getDirectAliasTarget = (
  reflection: DeclarationReflection,
  reflections: ReadonlyMap<string, DeclarationReflection>,
): DeclarationReflection | null => {
  if (reflection.kind !== ReflectionKind.TypeAlias) {
    return null;
  }

  const rendered = typeToString(reflection.type);
  const match = /^([A-Za-z_$][A-Za-z0-9_$]*)(?:<.*>)?$/.exec(rendered);
  return match?.[1] === undefined
    ? null
    : (reflections.get(match[1]) ?? null);
};

const buildReferencedTypeDoc = (
  options: CliOptions,
  git: GitSourceInfo | null,
  reflection: DeclarationReflection,
  reflections: ReadonlyMap<string, DeclarationReflection>,
  seen = new Set<string>(),
): ReferencedTypeDoc => {
  const properties: TypeMemberDoc[] = [];
  const methods: TypeMethodDoc[] = [];

  for (const child of reflection.children ?? []) {
    if (!isVisibleInstanceMember(child)) {
      continue;
    }

    if (
      child.kind === ReflectionKind.Property ||
      child.kind === ReflectionKind.Accessor ||
      child.kind === ReflectionKind.EnumMember
    ) {
      const getSignature = child.getSignature;
      properties.push({
        name: child.name,
        type: typeToString(getSignature?.type ?? child.type),
        summary: commentText(getSignature ?? child),
        readonly:
          child.flags.isReadonly || child.kind === ReflectionKind.Accessor,
        optional: child.flags.isOptional,
        inheritedFrom: getInheritedFrom(child),
        ...reflectionSource(options, git, getSignature ?? child),
      });
      continue;
    }

    if (child.kind === ReflectionKind.Method) {
      for (const signature of child.signatures ?? []) {
        methods.push({
          name: child.name,
          signature: methodSignatureText(child, signature),
          summary: commentText(signature) || commentText(child),
          inheritedFrom: getInheritedFrom(child),
          ...reflectionSource(options, git, signature),
        });
      }
    }
  }

  const aliasTarget = getDirectAliasTarget(reflection, reflections);
  if (
    aliasTarget !== null &&
    !seen.has(aliasTarget.name) &&
    properties.length === 0 &&
    methods.length === 0
  ) {
    const nextSeen = new Set(seen);
    nextSeen.add(reflection.name);
    const target = buildReferencedTypeDoc(
      options,
      git,
      aliasTarget,
      reflections,
      nextSeen,
    );
    properties.push(
      ...target.properties.map((property) => ({
        ...property,
        inheritedFrom: property.inheritedFrom ?? aliasTarget.name,
      })),
    );
    methods.push(
      ...target.methods.map((method) => ({
        ...method,
        inheritedFrom: method.inheritedFrom ?? aliasTarget.name,
      })),
    );
  }

  const summary = commentText(reflection);

  return {
    name: reflection.name,
    slug: kebabCase(reflection.name),
    kind: typedocKindName(reflection.kind),
    summary:
      summary ||
      (aliasTarget === null ? "" : `Alias of ${aliasTarget.name}.`),
    aliasOf: aliasTarget?.name ?? null,
    definition: declarationDefinition(reflection),
    properties: properties.sort((a, b) => a.name.localeCompare(b.name)),
    methods: methods.sort((a, b) => a.name.localeCompare(b.name)),
    ...reflectionSource(options, git, reflection),
  };
};

const buildAstReferencedTypeDoc = (
  checker: ts.TypeChecker,
  declarations: ReadonlyMap<
    string,
    ts.InterfaceDeclaration | ts.TypeAliasDeclaration
  >,
  options: CliOptions,
  git: GitSourceInfo | null,
  declaration: ts.InterfaceDeclaration | ts.TypeAliasDeclaration,
  seen = new Set<string>(),
): ReferencedTypeDoc => {
  const name = declaration.name.text;
  const properties: TypeMemberDoc[] = [];
  const methods: TypeMethodDoc[] = [];
  const nextSeen = new Set(seen);
  nextSeen.add(name);

  const inheritMembers = (
    target: ts.InterfaceDeclaration | ts.TypeAliasDeclaration,
    inheritedFrom: string,
  ): void => {
    if (nextSeen.has(target.name.text)) {
      return;
    }
    const inherited = buildAstReferencedTypeDoc(
      checker,
      declarations,
      options,
      git,
      target,
      nextSeen,
    );
    properties.push(
      ...inherited.properties.map((property) => ({
        ...property,
        inheritedFrom: property.inheritedFrom ?? inheritedFrom,
      })),
    );
    methods.push(
      ...inherited.methods.map((method) => ({
        ...method,
        inheritedFrom: method.inheritedFrom ?? inheritedFrom,
      })),
    );
  };

  let aliasOf: string | null = null;
  if (ts.isTypeAliasDeclaration(declaration)) {
    const target = parseTypeReference(declaration.type);
    const targetDeclaration =
      target === null ? undefined : declarations.get(target.unqualifiedName);
    if (targetDeclaration !== undefined) {
      aliasOf = targetDeclaration.name.text;
      inheritMembers(targetDeclaration, targetDeclaration.name.text);
    } else if (
      ts.isTypeQueryNode(declaration.type) &&
      ts.isQualifiedName(declaration.type.exprName) &&
      declaration.type.exprName.right.text === "Type" &&
      ts
        .getJSDocTags(declaration)
        .some((tag) => tag.tagName.text === "scriptingExpandSchema")
    ) {
      const resolved = checker.getTypeAtLocation(declaration);
      for (const symbol of checker.getPropertiesOfType(resolved)) {
        const symbolDeclaration = getSymbolDeclaration(symbol);
        if (
          symbolDeclaration === null ||
          !isInsideRepo(
            options.repoRoot,
            symbolDeclaration.getSourceFile().fileName,
          ) ||
          symbolDeclaration.getSourceFile().fileName.includes(
            "/node_modules/",
          )
        ) {
          continue;
        }
        const sourceNode = symbolDeclaration;
        properties.push({
          name: symbol.name,
          type: formatResolvedType(
            checker,
            checker.getTypeOfSymbolAtLocation(symbol, sourceNode),
            sourceNode,
          ),
          summary: getSymbolSummary(
            checker,
            symbol,
            symbolDeclaration,
          ),
          readonly: true,
          optional: (symbol.flags & ts.SymbolFlags.Optional) !== 0,
          inheritedFrom: null,
          ...getSourceInfo(options, git, sourceNode),
        });
      }
    }
  } else {
    for (const clause of declaration.heritageClauses ?? []) {
      if (clause.token !== ts.SyntaxKind.ExtendsKeyword) {
        continue;
      }
      for (const heritage of clause.types) {
        const reference = parseHeritageReference(heritage);
        const inherited =
          reference === null
            ? undefined
            : declarations.get(reference.unqualifiedName);
        if (inherited !== undefined) {
          inheritMembers(inherited, inherited.name.text);
        }
      }
    }

    for (const member of declaration.members) {
      const memberName =
        (ts.isPropertySignature(member) || ts.isMethodSignature(member)) &&
        member.name !== undefined
          ? getPropertyName(member.name)
          : null;
      if (memberName === null) {
        continue;
      }

      if (ts.isPropertySignature(member)) {
        properties.push({
          name: memberName,
          type: formatType(checker, member.type),
          summary: getSummary(member),
          readonly:
            member.modifiers?.some(
              (modifier) => modifier.kind === ts.SyntaxKind.ReadonlyKeyword,
            ) ?? false,
          optional: member.questionToken !== undefined,
          inheritedFrom: null,
          ...getSourceInfo(options, git, member),
        });
        continue;
      }

      if (!ts.isMethodSignature(member)) {
        continue;
      }

      const parameters = getParameterDocs(checker, member);
      const returnDoc = getReturnDoc(checker, member);
      methods.push({
        name: memberName,
        signature: methodSignature(memberName, parameters, returnDoc),
        summary: getSummary(member),
        inheritedFrom: null,
        ...getSourceInfo(options, git, member),
      });
    }
  }

  const typeParameters =
    declaration.typeParameters === undefined ||
    declaration.typeParameters.length === 0
      ? ""
      : `<${declaration.typeParameters
          .map((parameter) => parameter.name.text)
          .join(", ")}>`;
  const summary = getSummary(declaration);
  return {
    name,
    slug: kebabCase(name),
    kind: ts.isInterfaceDeclaration(declaration) ? "interface" : "type alias",
    summary: summary || (aliasOf === null ? "" : `Alias of ${aliasOf}.`),
    aliasOf,
    definition: ts.isInterfaceDeclaration(declaration)
      ? `interface ${name}${typeParameters}`
      : `type ${name}${typeParameters} = ${typeText(
          declaration.type,
          declaration.getSourceFile(),
        )}`,
    properties: properties.sort((left, right) =>
      left.name.localeCompare(right.name),
    ),
    methods: methods.sort((left, right) => left.name.localeCompare(right.name)),
    ...getSourceInfo(options, git, declaration),
  };
};

const collectReferencedTypeDocs = (
  checker: ts.TypeChecker,
  declarations: ReadonlyMap<
    string,
    ts.InterfaceDeclaration | ts.TypeAliasDeclaration
  >,
  options: CliOptions,
  git: GitSourceInfo | null,
  project: ProjectReflection,
  rootReferences: ReadonlySet<string>,
): ReferencedTypeDoc[] => {
  const reflections = buildTypeReflectionMap(options, project);
  const pending = Array.from(rootReferences);
  const seen = new Set<string>();
  const docs: ReferencedTypeDoc[] = [];

  for (let index = 0; index < pending.length; index += 1) {
    const name = pending[index];
    if (
      name === undefined ||
      seen.has(name) ||
      BUILTIN_TYPE_NAMES.has(name) ||
      TYPE_REFERENCE_WRAPPERS.has(name)
    ) {
      continue;
    }
    seen.add(name);

    const reflection = reflections.get(name);
    const declaration = declarations.get(name);
    if (reflection === undefined && declaration === undefined) {
      continue;
    }
    if (
      declaration !== undefined &&
      ts
        .getJSDocTags(declaration)
        .some((tag) => tag.tagName.text === "internal")
    ) {
      continue;
    }

    const doc =
      declaration !== undefined && ts.isTypeAliasDeclaration(declaration)
        ? buildAstReferencedTypeDoc(
            checker,
            declarations,
            options,
            git,
            declaration,
          )
        : reflection !== undefined
          ? buildReferencedTypeDoc(options, git, reflection, reflections)
          : buildAstReferencedTypeDoc(
              checker,
              declarations,
              options,
              git,
              declaration!,
            );
    docs.push(doc);

    const nestedReferences = new Set<string>();
    collectTypeNameTokens(doc.definition, nestedReferences);
    for (const property of doc.properties) {
      collectTypeNameTokens(property.type, nestedReferences);
    }
    for (const method of doc.methods) {
      collectTypeNameTokens(method.signature, nestedReferences);
    }
    for (const nested of nestedReferences) {
      if (!seen.has(nested) && !pending.includes(nested)) {
        pending.push(nested);
      }
    }
  }

  return docs.sort((a, b) => a.name.localeCompare(b.name));
};

const typedocEntryPoints = (
  program: ts.Program,
  options: CliOptions,
  declarations: ReadonlyMap<
    string,
    ts.InterfaceDeclaration | ts.TypeAliasDeclaration
  >,
  typeReferences: ReadonlySet<string>,
): readonly string[] => {
  const entryPoints = new Set<string>();
  const addSourceFile = (fileName: string): void => {
    if (
      fileName.includes("/node_modules/") ||
      fileName.endsWith(".test.ts") ||
      !isInsideRepo(options.repoRoot, fileName)
    ) {
      return;
    }
    entryPoints.add(relative(options.repoRoot, fileName).replaceAll("\\", "/"));
  };

  addSourceFile(options.sourceFile);
  for (const sourceFile of program.getSourceFiles()) {
    const relativePath = relative(options.repoRoot, sourceFile.fileName).replaceAll(
      "\\",
      "/",
    );
    if (
      relativePath.startsWith("app/src/shared/") ||
      relativePath.startsWith("app/src/renderer/apps/game/") ||
      relativePath.startsWith("packages/core/src/") ||
      relativePath.startsWith("packages/game/src/")
    ) {
      addSourceFile(sourceFile.fileName);
    }
  }
  for (const reference of typeReferences) {
    const declaration = declarations.get(reference);
    if (declaration !== undefined) {
      addSourceFile(declaration.getSourceFile().fileName);
    }
  }
  return Array.from(entryPoints).sort();
};

