type ScriptEventReference = {
  readonly name: string;
  readonly payload: string;
};

const collectScriptEventReferences = (
  checker: ts.TypeChecker,
  declarations: ReadonlyMap<
    string,
    ts.InterfaceDeclaration | ts.TypeAliasDeclaration
  >,
): readonly ScriptEventReference[] => {
  const declaration = declarations.get("Event");
  if (declaration === undefined) {
    return [];
  }

  const eventType = checker.getTypeAtLocation(declaration);
  const variants = eventType.isUnion() ? eventType.types : [eventType];
  const references: ScriptEventReference[] = [];
  for (const variant of variants) {
    const typeProperty = checker.getPropertyOfType(variant, "type");
    if (typeProperty === undefined) {
      continue;
    }
    const typeDeclaration = getSymbolDeclaration(typeProperty) ?? declaration;
    const discriminator = checker.getTypeOfSymbolAtLocation(
      typeProperty,
      typeDeclaration,
    );
    if (!discriminator.isStringLiteral()) {
      continue;
    }

    const fields = checker
      .getPropertiesOfType(variant)
      .filter((property) => property.name !== "type")
      .map((property) => {
        const propertyDeclaration =
          getSymbolDeclaration(property) ?? declaration;
        const optional =
          (property.flags & ts.SymbolFlags.Optional) === 0 ? "" : "?";
        const propertyType = (
          ts.isPropertySignature(propertyDeclaration) &&
          propertyDeclaration.type !== undefined
            ? typeText(
                propertyDeclaration.type,
                propertyDeclaration.getSourceFile(),
              )
            : formatResolvedType(
                checker,
                checker.getTypeOfSymbolAtLocation(
                  property,
                  propertyDeclaration,
                ),
                propertyDeclaration,
              )
        ).replace(/\s+/g, " ");
        return `${property.name}${optional}: ${propertyType}`;
      });

    references.push({
      name: discriminator.value,
      payload: fields.length === 0 ? "{}" : `{ ${fields.join("; ")} }`,
    });
  }

  return references.sort((left, right) => left.name.localeCompare(right.name));
};

